/**
 * 開発中はログインを挟まずに画面を触れるようにする。
 *
 * 変更するたびにメールのリンクを踏み直すのは手数が多いうえ、
 * リンクの送信には回数の制限もある。作っている間はサーバーに触らず、
 * 端末に貯めた分だけで動かす。
 *
 * 本番の build では NODE_ENV が production になるので、この値は必ず false
 * になる。環境変数を間違えて Vercel 側に置いてしまっても、公開されたものが
 * 素通しになることはない。production では下の条件ごと定数に畳まれるので、
 * ローカル用の道は本番のバンドルに残らない。
 *
 * 開発中に認証そのものを試したいときは .env.local に
 * NEXT_PUBLIC_DEV_NO_AUTH=0 と書く。
 */
export const DEV_NO_AUTH =
  process.env.NODE_ENV !== "production" && process.env.NEXT_PUBLIC_DEV_NO_AUTH !== "0";

